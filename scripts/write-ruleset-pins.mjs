import {createHash} from 'node:crypto';
import {readFile,writeFile,rename,rm} from 'node:fs/promises';
import {GAME_IDS,catalogDefinition,canonicalJSON} from '../src/catalog-data.js';
const FORMAT='open-table.ruleset-binding.v1',files=['src/adaptations.js','src/author-request.js','src/app.js','src/designer-fixtures.js','src/games.js','src/one-key.js','src/pack.js','src/saved-match.js'];
const sha256=bytes=>createHash('sha256').update(bytes).digest('hex'),sourceDigests={};
for(const path of files)sourceDigests[path]=sha256(await readFile(new URL('../'+path,import.meta.url)));
const pins={};
for(const gameId of GAME_IDS)pins[gameId]='sha256:'+sha256(Buffer.from(canonicalJSON({format:FORMAT,gameId,catalog:catalogDefinition(gameId),sources:sourceDigests}),'utf8'));
const output='// Generated by scripts/write-ruleset-pins.mjs from current source bytes.\nexport const RULESET_PINS = Object.freeze('+JSON.stringify(pins,null,2)+');\nexport const RULESET_SOURCE_DIGESTS = Object.freeze('+JSON.stringify(sourceDigests,null,2)+');\n';
const target=new URL('../src/ruleset-pins.js',import.meta.url);
if(process.argv.includes('--check')){
 let existing='';try{existing=await readFile(target,'utf8');}catch{}
 if(existing!==output)throw new Error('Ruleset pins are missing or stale. Run node scripts/write-ruleset-pins.mjs before serving, testing, or packaging.');
}else{
 const temporary=new URL(target.href+'.tmp-'+process.pid);
 try{await writeFile(temporary,output,'utf8');await rename(temporary,target);}finally{await rm(temporary,{force:true});}
}
console.log(JSON.stringify({format:FORMAT,checked:process.argv.includes('--check'),pins,sourceDigests},null,2));
